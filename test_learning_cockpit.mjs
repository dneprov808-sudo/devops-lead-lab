import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
const read=p=>readFileSync(new URL(p,import.meta.url),"utf8");
const app=read("./web/app.js");
const helpers=app.slice(app.indexOf("function cockpitMatch("),app.indexOf("(function initCockpit()"));
const {cockpitMatch,cockpitStepIndex}=new Function(helpers+"\nreturn {cockpitMatch,cockpitStepIndex};")();
const entries=[{search:"Production Simulator · HA",id:"ha"},{search:"Kubernetes Helm",id:"k8s"},{search:"Каталог технологий",id:"hub"}];
assert(cockpitMatch(entries," HA production ")[0].id==="ha","case-insensitive multiword match");
assert(cockpitMatch(entries,"технологий")[0].id==="hub","Cyrillic search");
assert(cockpitMatch(entries,"not found").length===0,"empty result");
assert(cockpitMatch(entries,"").length===3,"empty query");
assert(cockpitStepIndex(-1,4)===0&&cockpitStepIndex(4,4)===3,"bounded runbook steps");
assert(cockpitStepIndex(2,4)===2&&cockpitStepIndex(NaN,4)===0,"valid and invalid step");
const guide=JSON.parse(read("./learning/knowledge.json")).find(g=>g.id==="linux");
const source=read("./web/learning.js").split("\n(() => {")[0];
const store=new Map([["academy-review-v1","untouched"]]);
let updates=0;
const storage={getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value)};
const reader=new Function("localStorage","window",source+"\nreturn {theoryChapters,readTheoryPosition};")(storage,{academyUpdateReading(){updates++}});
const el=(tag,text,cls)=>({tag,text,cls,children:[],attrs:{},append(...n){this.children.push(...n)},replaceChildren(...n){this.children=n},setAttribute(k,v){this.attrs[k]=v}});
const button=(text,fn)=>Object.assign(el("button",text),{fn});
let copied=null;
const render=(api=reader)=>api.theoryChapters(guide,el,button,(text,url)=>({tag:"a",text,url}),s=>copied=s);
const parts=root=>({list:root.children.find(n=>n.cls==="reader-rail").children[1],panels:root.children.find(n=>n.cls==="reader-body").children.filter(n=>n.cls==="theory-chapter")});
const initial=parts(render());
assert(initial.panels[0].open&&initial.panels.slice(1).every(n=>n.hidden),"default first chapter");
initial.list.children[4].fn();
assert(reader.readTheoryPosition().chapter===guide.chapters[4].id&&updates===1,"selected chapter persisted");
assert(store.get("academy-review-v1")==="untouched","existing learning key untouched");
const restored=parts(render());
assert(restored.panels[4].open&&restored.panels.filter(n=>!n.hidden).length===1,"resume after render");
restored.panels[4].children.find(n=>n.tag==="button"&&n.text==="Копировать код").fn();
assert(copied===guide.chapters[4].snippet.code,"verbatim snippet copy");
store.set("academy-ui-reading-v12",JSON.stringify({guide:guide.id,chapter:"unknown"}));
assert(parts(render()).panels[0].open,"stale chapter falls back");
store.set("academy-ui-reading-v12","invalid JSON");
assert(reader.readTheoryPosition()===null&&parts(render()).panels[0].open,"invalid preference falls back");
const denied=new Function("localStorage","window",source+"\nreturn {theoryChapters,readTheoryPosition};")({getItem(){throw Error("denied")},setItem(){throw Error("denied")}}, {});
const d=parts(render(denied));d.list.children[1].fn();
assert(d.panels[1].open&&denied.readTheoryPosition()===null,"storage denial does not break reader");
console.log("Cockpit search, step bounds, reading persistence and copy PASS");
