import assert from "node:assert/strict";
import {planQueue} from "./queue_v12.mjs";
import {planConsumer} from "./consumer.mjs";
import {canonical,render} from "./bus.mjs";
import {mkdtempSync,writeFileSync,readFileSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {spawnSync} from "node:child_process";
import {fileURLToPath} from "node:url";
const s={control_ref:"academy/orchestration-v1",control_commit:"a".repeat(40),state_blob:"b".repeat(40),revision:1,task_id:"LAB-001",task_ref:"training/lead-cohort-01",task_status:"assigned",accepted_ids:[],pending_ids:[],implementation_commit:null};
const options={complete:true,finalStateBlob:s.state_blob,finalControlCommit:s.control_commit};
const c=(issues=[],snapshot=s,verified={},opt={})=>planConsumer(issues,snapshot,verified,{...options,...opt});
const e=(over={},channel="live")=>({bus_version:1,channel,handoff:{handoff_version:1,handoff_id:"student/LAB-001/submitted/start-1",from:"student",to:"orchestrator",task_id:"LAB-001",event:"submitted",observed_state_revision:1,control_ref:s.control_ref,observed_control_commit:s.control_commit,artifact_ref:s.task_ref,artifact_commit:null,result:"partial",summary:"Synthetic",evidence:[],proposed_status:"in_progress",next_action:"Review",limitations:[],...over}});
const row=(n,v=e(),state="open")=>({number:n,state,user:{login:"dneprov808-sudo"},...render(v)});
const proof=v=>({[v.handoff.handoff_id]:{source:"independent_operator_review",envelope_canonical:canonical(v),state_blob:s.state_blob,control_commit:s.control_commit,review_ref:"synthetic fixture",artifact_commit:null,checks:["start_confirmation"]}});
assert.equal(planQueue(s,c()).queue[0].role,"student");
assert.equal(planQueue(s,c([],s,{}, {channel:"test"})).status,"BLOCKED");
assert.equal(planQueue(s,{...c(),control_commit:"c".repeat(40)}).status,"BLOCKED");
assert.equal(planQueue(s,{...c(),task_status:"completed"}).status,"BLOCKED");
assert.equal(planQueue(s,{...c(),writes:1}).status,"BLOCKED");
assert.equal(planQueue(s,c([row(1)])).queue[0].role,"orchestrator");
const review=e({proposed_status:null});
assert.equal(planQueue(s,c([row(1,review)])).queue[0].action,"Reconcile review_only");
assert.equal(planQueue({...s,pending_ids:[e().handoff.handoff_id]},c([row(1)],{...s,pending_ids:[e().handoff.handoff_id]})).queue[0].action,"Reconcile already_pending");
assert.equal(planQueue(s,c([row(1,e(),"closed")])).queue[0].action,"Reconcile closed_unreconciled");
const result=c([row(1)],s,proof(e()));
assert.equal(planQueue(s,result).queue[0].role,"orchestrator");
assert.equal(planQueue(s,{...result,proposals:[]}).status,"BLOCKED");
assert.equal(planQueue(s,{...result,proposals:[{...result.proposals[0],expected_revision:2}]}).status,"BLOCKED");
const other=e({handoff_id:"student/LAB-001/submitted/start-2"});
const conflict=c([row(1),row(2,other)],s,{...proof(e()),...proof(other)});
assert.equal(planQueue(s,conflict).queue.length,2);
assert.ok(planQueue(s,conflict).queue.every(x=>x.blocking&&x.role==="orchestrator"));
for(const status of ["blocked_report","rejected_transition","collision","quarantined","stale"])assert.equal(planQueue(s,{...c(),journal:[{status,handoff_id:"fixture"}]}).queue[0].role,"orchestrator");
assert.equal(planQueue(s,{...c(),journal:[{status:"unknown",handoff_id:"fixture"}]}).status,"BLOCKED");
assert.equal(planQueue(s,{...c(),journal:[{status:"collision",handoff_id:"x"},{status:"collision",handoff_id:"x"}]}).status,"BLOCKED");
const dir=mkdtempSync(join(tmpdir(),"academy-queue-"));
try{
 const input=join(dir,"in.json"),out=join(dir,"out.json"),cli=fileURLToPath(new URL("./queue_v12_cli.mjs",import.meta.url));
 writeFileSync(input,JSON.stringify({issues:[],snapshot:s,verified:{},options:{...options,finalControlCommit:"c".repeat(40)}}));
 assert.equal(spawnSync(process.execPath,[cli,input,out]).status,2);
 assert.equal(JSON.parse(readFileSync(out)).status,"BLOCKED");
 rmSync(out);
 writeFileSync(input,JSON.stringify({issues:[],snapshot:s,verified:{},options}));
 assert.equal(spawnSync(process.execPath,[cli,input,out]).status,0);
 assert.equal(JSON.parse(readFileSync(out)).input_sha256.length,64);
 assert.notEqual(spawnSync(process.execPath,[cli,input,out]).status,0);
}finally{rmSync(dir,{recursive:true,force:true})}
console.log("Queue/Consumer integration PASS");
