import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const code=readFileSync(new URL("./site/templates/progress.js",import.meta.url),"utf8");
const {siteValidate,siteMerge,siteRead,siteWrite,SITE_KEYS}=new Function(code+"\nreturn {siteValidate,siteMerge,siteRead,siteWrite,SITE_KEYS};")();
const backup=(seen=[],last=null,drafts={},ratings={})=>({format:"academy-site-progress",version:1,reading:{seen,last},interview:{drafts,ratings}});
const base=backup(["linux-01"],{id:"linux",chapter:"linux-01"},{"K8S-001":"local"},{"K8S-001":"review"});
const incoming=backup(["linux-01","linux-02"],{id:"k8s",chapter:"k8s-01"},{"K8S-001":"other","K8S-002":"new"},{"K8S-001":"ok"});
const merged=siteMerge(base,incoming);
assert.deepEqual(merged.backup.reading.seen,["linux-01","linux-02"]);
assert.equal(merged.backup.reading.last.chapter,"linux-01");
assert.equal(merged.backup.interview.drafts["K8S-001"],"local");
assert.equal(merged.backup.interview.drafts["K8S-002"],"new");
assert.equal(merged.backup.interview.ratings["K8S-001"],"review");
assert.equal(merged.conflicts,2);
assert.deepEqual(siteMerge(base,base).backup.reading,base.reading);
assert.throws(()=>siteValidate({...base,version:2}));
assert.throws(()=>siteValidate(backup(["__proto__"])));
assert.throws(()=>siteValidate(backup([],null,JSON.parse('{"constructor":"bad"}'))));
assert.throws(()=>siteValidate(backup([],null,{},{"K8S-001":"verified"})));
assert.throws(()=>siteValidate(backup([],{id:"linux",chapter:1})));
const map=new Map([["other-key","preserved"]]);
const storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
siteWrite(storage,base);
assert.equal(siteRead(storage).reading.last.chapter,"linux-01");
assert.equal(map.get("other-key"),"preserved");
siteWrite(storage,merged.backup);
assert.equal(siteRead(storage).interview.drafts["K8S-002"],"new");
const before=new Map(map);let fail=true;
const failing={...storage,setItem(k,v){if(k===SITE_KEYS.interview&&fail){fail=false;throw Error("quota")}map.set(k,v)}};
assert.throws(()=>siteWrite(failing,backup(["new-01"])));
assert.deepEqual([...map],[...before]);
console.log("Static site progress: merge, validation, stable IDs, unrelated data and rollback PASS");
