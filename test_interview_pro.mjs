import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=path=>fs.readFileSync(new URL(path,import.meta.url),'utf8');
const source=read('./web/interview-bank.js')+'\n'+read('./web/interview-pro.js')+'\n'+read('./web/mock.js');
const {bank,normalize,validate,filter,pool,plan,exportResult}=new Function(source+';return {bank:INTERVIEW_PRO_BANK,normalize:proNormalize,validate:proValidate,filter:proFilter,pool:proMockPool,plan:mockPlan,exportResult:mockExport}')();
assert.ok(bank.length>=35 && bank.length<=738);
assert.ok(validate(bank));
assert.equal(new Set(bank.map(q=>q.id)).size,bank.length);
assert.ok(bank.every(q=>q.answer.length>=100 && q.practice.length>=20 && q.rubric.length>=20));
assert.equal(filter(bank,{query:'k8s-001'}).length,1);
assert.ok(filter(bank,{topic:'Kubernetes',level:'lead'}).length>0);
assert.ok(filter(bank,{section:'storage'}).length>0);
assert.equal(filter(bank,{query:'___not_a_question___'}).length,0);
assert.equal(validate([bank[0],bank[0]]),false);
assert.equal(validate([bank[0],{...bank[0],id:'K8S-999'}]),false);
assert.equal(validate([{...bank[0],answer:''}]),false);
assert.equal(validate([{...bank[0],source:'javascript:alert(1)'}]),false);
assert.equal(validate([{...bank[0],level:'unknown'}]),false);
const app=read('./web/app.js');
const legacy=new Function(app.slice(0,app.indexOf('const $=id=>'))+';return BANK.flatMap(r=>r.slice(1).map(q=>q[0]))')();
const diagnostic=new Function(read('./web/accelerator.js')+';return ACC_QUESTIONS.map(q=>q[1])')();
const existing=new Set([...legacy,...diagnostic].map(normalize));
assert.ok(bank.every(q=>!existing.has(normalize(q.question))));
for(const [minutes,count] of [[30,6],[60,12],[90,18]]){
 const questions=plan(minutes,pool(bank),()=>0.5);
 assert.equal(questions.length,count);
 assert.equal(new Set(questions.map(q=>q[4])).size,count);
 const result=exportResult(minutes,questions,['test'],0,1000);
 assert.equal(result.assessment,'unassessed');
 assert.equal(result.responses[0].question_id,questions[0][4]);
 assert.equal(result.responses[0].answer,'test');
 assert.equal(Object.hasOwn(result.responses[0],'rubric'),false);
}
const html=read('./web/index.html'),portal=read('./portal.py');
assert.ok(html.indexOf('src="/interview-bank.js"')<html.indexOf('src="/interview-pro.js"'));
assert.ok(html.indexOf('src="/interview-pro.js"')<html.indexOf('src="/mock.js"'));
assert.ok(html.includes('id="interview-pro-center"')&&html.includes('data-page="interview-pro"'));
assert.ok(portal.includes('"/interview-bank.js"')&&portal.includes('"/interview-pro.js"'));
console.log('Interview Pro contract PASS');
