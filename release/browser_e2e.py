"""Real browser -> local HTTP portal. No remote writes. Requires Playwright Chromium."""
import os, pathlib, subprocess, sys, time, tempfile, urllib.request
from playwright.sync_api import sync_playwright, expect
ROOT=pathlib.Path(__file__).resolve().parents[1]
def main():
    with tempfile.TemporaryDirectory() as tmp:
        env=dict(os.environ,ACADEMY_DATA_DIR=tmp)
        # Refuse to touch an already running portal.
        try:
            urllib.request.urlopen("http://127.0.0.1:8080/api/version",timeout=1).close()
        except OSError: pass
        else: raise RuntimeError("Stop the existing portal before E2E")
        proc=subprocess.Popen([sys.executable,"portal.py"],cwd=ROOT,env=env,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        try:
            for _ in range(60):
                if proc.poll() is not None: raise RuntimeError("portal exited")
                try:
                    urllib.request.urlopen("http://127.0.0.1:8080/api/version",timeout=1).close()
                    break
                except OSError: time.sleep(.2)
            else: raise RuntimeError("portal startup timeout")
            with sync_playwright() as p:
                browser=p.chromium.launch(headless=True,executable_path=os.environ.get("ACADEMY_CHROMIUM") or None)
                page=browser.new_page(permissions=["clipboard-read", "clipboard-write"])
                errors=[]
                page.on("pageerror",lambda e:errors.append(str(e)))
                page.goto("http://127.0.0.1:8080/",wait_until="domcontentloaded")
                expect(page.locator("#home h1")).to_have_text("Мой день")
                expect(page.locator("#hub")).to_be_hidden()
                expect(page.locator("#home-answers")).to_have_text("0")
                expect(page.locator("html")).to_have_attribute("data-theme", "light")
                page.locator("#theme-toggle").click()
                expect(page.locator("html")).to_have_attribute("data-theme", "dark")
                expect(page.locator("#theme-toggle")).to_have_attribute("aria-pressed", "true")
                page.reload(wait_until="domcontentloaded")
                expect(page.locator("html")).to_have_attribute("data-theme", "dark")
                page.locator("#theme-toggle").click()
                expect(page.locator("html")).to_have_attribute("data-theme", "light")
                expect(page.locator("#home-task-title")).to_be_visible()
                page.get_by_role("button", name="Где и как запускать").click()
                expect(page.locator("#deploy")).to_be_visible()
                expect(page.locator("nav button[data-page=deploy]")).to_have_attribute("aria-current", "page")
                expect(page.locator("#deploy .deploy-card")).to_have_count(9)
                expect(page.locator("#deploy .deploy-card:visible")).to_have_count(1)
                expect(page.locator("#deploy-portal")).to_be_visible()
                page.get_by_role("link", name="04 · Production Simulator · HA", exact=True).click()
                expect(page.locator("#deploy-ha")).to_be_visible()
                expect(page.locator("#deploy-portal")).to_be_hidden()
                expect(page.locator("#deploy .deploy-card:visible")).to_have_count(1)
                assert page.url.endswith("#deploy-ha")
                page.reload(wait_until="domcontentloaded")
                expect(page.locator("#deploy-ha")).to_be_visible()
                expect(page.locator("#deploy .deploy-card:visible")).to_have_count(1)
                assert page.locator("#deploy-ha pre").first.inner_text().startswith("unset DOCKER_HOST")
                expect(page.locator("#workspace-current")).to_have_text("Развёртывание")
                code=page.locator("#deploy-ha .deploy-command").first
                code.get_by_role("button",name="Копировать команды").click()
                expect(code.locator(".copy-feedback")).to_contain_text("Скопировано")
                assert page.evaluate("navigator.clipboard.readText()")==code.locator("pre").inner_text()
                expect(page.locator("#deploy-ha .deploy-command:visible")).to_have_count(1)
                page.locator("#deploy-ha .cockpit-step-controls").get_by_role("button",name="Далее →").click()
                expect(page.locator("#deploy-ha .deploy-command").nth(1)).to_be_visible()
                expect(code).to_be_hidden()
                page.locator("#deploy-ha").get_by_role("button",name="Все команды",exact=True).click()
                expect(page.locator("#deploy-ha .deploy-command:visible")).to_have_count(4)
                page.locator("#deploy-ha").get_by_role("button",name="Пошаговый режим",exact=True).click()
                page.set_viewport_size({"width": 390, "height": 844})
                assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
                expect(page.locator("#workspace-nav")).to_be_hidden()
                page.locator("#menu-toggle").click()
                expect(page.locator("#workspace-nav")).to_be_visible()
                expect(page.locator("#menu-toggle")).to_have_attribute("aria-expanded","true")
                page.keyboard.press("Escape")
                expect(page.locator("#workspace-nav")).to_be_hidden()
                page.locator("#menu-toggle").click()
                page.locator('nav details[data-workspace="learn"] summary').click()
                page.locator('nav button[data-page="hub"]').click()
                expect(page.locator("#workspace-nav")).to_be_hidden()
                expect(page.locator("#hub")).to_be_visible()
                page.set_viewport_size({"width": 1280, "height": 720})
                expect(page.locator("#hub-grid .hub-tile")).to_have_count(20)
                page.locator("#hub-grid .hub-tile").first.get_by_role("button",name="Открыть материалы →").click()
                expect(page.locator("#hub-catalog")).to_be_hidden()
                expect(page.locator("#hub-section-theory")).to_be_visible()
                expect(page.locator("#hub-section-theory .theory-chapter")).to_have_count(3)
                expect(page.locator("#hub-section-theory .theory-chapter").first).to_have_attribute("open", "")
                page.locator("#hub-section-theory .reader-chapter-list button").nth(1).click()
                expect(page.locator("#hub-section-theory .theory-chapter:visible")).to_have_count(1)
                expect(page.locator("#hub-section-theory .reader-chapter-list button").nth(1)).to_have_attribute("aria-pressed","true")
                expect(page.locator("#hub-section-theory .theory-chapter").nth(1).locator("pre")).to_be_visible()
                page.keyboard.press("Control+k")
                expect(page.locator("#cockpit-search")).to_be_visible()
                page.locator("#cockpit-search-input").fill("Production Simulator HA")
                expect(page.locator("#cockpit-search-results button")).to_have_count(1)
                page.keyboard.press("Escape")
                expect(page.locator("#cockpit-search")).to_be_hidden()
                page.locator("#hub-detail-nav").get_by_role("button",name="Практические задания").click()
                expect(page.locator("#hub-section-practice")).to_be_visible()
                expect(page.locator("#hub-section-theory")).to_be_hidden()
                page.locator("#hub-close").click()
                expect(page.locator("#hub-catalog")).to_be_visible()
                page.goto("http://127.0.0.1:8080/#home",wait_until="domcontentloaded")
                expect(page.locator("#cockpit-resume")).to_be_enabled()
                page.locator("#cockpit-resume").click()
                expect(page.locator("#hub-section-theory .theory-chapter").nth(1)).to_be_visible()
                page.locator("#hub-close").click()

                page.locator('nav details[data-workspace="interview"] summary').click()
                page.locator('nav button[data-page="interview-pro"]').click()
                expect(page.locator("#interview-pro-center h2")).to_be_visible()
                page.locator("#interview-pro-center textarea").fill("Synthetic E2E answer")
                page.get_by_role("button",name="Показать разбор",exact=True).click()
                expect(page.get_by_text("Подробный ответ",exact=True)).to_be_visible()
                page.locator("#interview-pro-center").get_by_label("Самооценка",exact=True).select_option("2")
                page.get_by_label("Ошибка",exact=True).fill("synthetic gap")
                page.get_by_role("button",name="Сохранить попытку локально").click()
                expect(page.get_by_text("Сохранено ·",exact=False)).to_be_visible()
                assert len(page.request.get("http://127.0.0.1:8080/api/v11/export").json()["events"])==1
                page.locator('nav button[data-page="mock"]').click()
                page.locator("#mock details").first.locator("summary").click()
                page.locator("#mock-center").get_by_role("button",name="30 мин",exact=True).click()
                expect(page.locator("#mock-center textarea")).to_be_visible()
                page.get_by_role("button",name="Начать структурированное интервью").click()
                page.get_by_label("Ответ структурированного интервью").fill("resumable synthetic answer")
                page.reload(wait_until="domcontentloaded")
                page.locator('nav button[data-page="mock"]').click()
                expect(page.get_by_label("Ответ структурированного интервью")).to_have_value("resumable synthetic answer")
                page.locator('nav details[data-workspace="progress"] summary').click()
                page.locator('nav button[data-page="study-v11"]').click()
                expect(page.get_by_role("button",name="Экспорт черновиков",exact=True)).to_be_visible()
                page.get_by_role("button",name="Экспорт черновиков",exact=True).click()
                expect(page.get_by_label("Локальная копия черновиков")).to_have_value(__import__("re").compile("mock-active"))
                assert page.request.get("http://127.0.0.1:8080/api/v12/assessment").json()["canonical_grade"]=="unchanged"
                assert len(page.request.get("http://127.0.0.1:8080/api/v12/labs").json()["kubernetes"])==20
                assert len(page.request.get("http://127.0.0.1:8080/api/v12/leadership").json())==12
                assert page.request.get("http://127.0.0.1:8080/api/version").json()["release"].startswith("Academy v12")
                assert page.request.post("http://127.0.0.1:8080/api/test").status==403
                assert page.request.get("http://127.0.0.1:8080/portal.py").status==404
                assert not errors,errors
                browser.close()
        finally:
            proc.terminate()
            try: proc.wait(timeout=5)
            except subprocess.TimeoutExpired: proc.kill(); proc.wait()
if __name__=="__main__": main()
